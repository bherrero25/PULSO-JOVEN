-- Imitación mínima de Supabase para probar los textos de sql/: base de datos desechable «pulso_prueba» con el esquema auth,
-- los roles anon y authenticated, la tabla de movimientos y dos personas. Lo ejecuta ejecutar_sql.sh.
drop database if exists pulso_prueba;
create database pulso_prueba;
\c pulso_prueba
do $$ begin
  if not exists (select from pg_roles where rolname = 'anon') then create role anon nologin; end if;
  if not exists (select from pg_roles where rolname = 'authenticated') then create role authenticated nologin; end if;
end $$;
create schema auth;
create table auth.users (id uuid primary key);
create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('prueba.uid', true), '')::uuid $$;
grant usage on schema auth to anon, authenticated;
grant execute on function auth.uid() to anon, authenticated;
grant usage on schema public to anon, authenticated;
create table public.pj_transacciones (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users (id), fecha date not null, descripcion text not null, importe numeric not null,
  tipo text, categoria text, medio text, cuenta text, created_at timestamptz default now()
);
alter table public.pj_transacciones enable row level security;
