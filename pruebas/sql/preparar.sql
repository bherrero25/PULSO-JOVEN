-- debe_fallar('…'): la orden tiene que dar error (permiso, comprobación o RLS); si no falla, la prueba falla
create function public.debe_fallar(orden text) returns void language plpgsql as $$
begin
  execute orden;
  raise exception 'DEBÍA FALLAR y no falló: %', orden;
exception when others then
  if sqlerrm like 'DEBÍA FALLAR%' then raise; end if;
end $$;
grant execute on function public.debe_fallar(text) to anon, authenticated;
